package mcputil

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"github.com/bhaskarjha-dev/vivechak/internal/core"
	vembed "github.com/bhaskarjha-dev/vivechak/internal/embed"
	store "github.com/bhaskarjha-dev/vivechak/internal/store"
	sdkmcp "github.com/modelcontextprotocol/go-sdk/mcp"
)

// SavePlanInput holds the arguments for vivechak_save_plan.
type SavePlanInput struct {
	ProjectRoot      string `json:"project_root,omitempty"       jsonschema:"workspace root path"`
	Scope            string `json:"scope,omitempty"              jsonschema:"research scope: project | decision | comparison"`
	Content          string `json:"content"                      jsonschema:"the generated plan content (Markdown)"`
	DecisionsContent string `json:"decisions_content,omitempty" jsonschema:"the generated initial decision registry or ADR content"`
	ID               string `json:"id,omitempty"                 jsonschema:"universal identifier for comparison or decision (e.g. C-01, D-01)"`
	DecisionID       string `json:"decision_id,omitempty"        jsonschema:"identifier for decision scope (e.g. D-01) or comparison scope (e.g. C-01)"`
	ComparisonID     string `json:"comparison_id,omitempty"      jsonschema:"optional alias for decision_id in comparison scope (e.g. C-01)"`
	Slug             string `json:"slug,omitempty"               jsonschema:"URL-safe slug for the decision (e.g. database-selection)"`
}

func registerSavePlan(server *sdkmcp.Server) {
	sdkmcp.AddTool(server,
		&sdkmcp.Tool{
			Name:  "vivechak_save_plan",
			Title: "Save Research Plan",
			Description: "Validate and persist an agent-generated research plan. " +
				"At project scope: validates DAG structure and saves RESEARCH-PIPELINE.md + DECISIONS.md. " +
				"Dependencies are plain session IDs (e.g. 'T0-01, T0-03'); do not include qualifiers like 'Hard:' or 'Soft:'. " +
				"At decision scope: validates routing and saves [ID]-PLAN.md + proposed ADR. " +
				"At comparison scope: validates and saves the completed comparison research output / WEP matrix. " +
				"Runs L1-L2 validation before saving — blocks on structural errors, warns on quality issues.",
			Annotations: &sdkmcp.ToolAnnotations{
				ReadOnlyHint:    false,
				IdempotentHint:  true,
				DestructiveHint: BoolPtr(false),
				OpenWorldHint:   BoolPtr(false),
			},
		},
		handleSavePlan,
	)
}

func handleSavePlan(ctx context.Context, _ *sdkmcp.CallToolRequest, in SavePlanInput) (*sdkmcp.CallToolResult, Envelope, error) {
	const tool = "vivechak_save_plan"

	// Resolve workspace
	root, err := core.ResolveWorkspace(in.ProjectRoot)
	if err != nil {
		return ErrorResult(tool, err,
			"Initialize a workspace first with vivechak_init, or provide project_root explicitly.")
	}

	// Parse scope
	scope := core.ScopeProject
	if in.Scope != "" {
		s, ok := core.ScopeFromString(in.Scope)
		if !ok {
			return ErrorResult(tool, fmt.Errorf("invalid scope %q", in.Scope),
				"Use scope 'project', 'decision', or 'comparison'.")
		}
		scope = s
	} else if core.WorkspaceExists(root) {
		info := core.InspectWorkspace(root)
		if info.Scope != "" {
			scope = info.Scope
		}
	}

	// Validate content
	if strings.TrimSpace(in.Content) == "" {
		return ErrorResult(tool, fmt.Errorf("content is required"),
			"Provide the plan content generated by the generator prompt.")
	}

	if err := validateContentSize(in.Content); err != nil {
		return ErrorResult(tool, err, "Reduce content size or split into multiple artifacts.")
	}

	// Support universal id and comparison_id aliases
	if in.DecisionID == "" && in.ID != "" {
		in.DecisionID = in.ID
	}
	if in.DecisionID == "" && in.ComparisonID != "" {
		in.DecisionID = in.ComparisonID
	}
	if scope == core.ScopeComparison && (in.DecisionID == "D-NEW" || in.DecisionID == "C-NEW") {
		in.DecisionID = ""
	}

	// Auto-extract ID from plan content if not explicitly provided
	if in.DecisionID == "" && (scope == core.ScopeDecision || scope == core.ScopeComparison) {
		// First check for explicit markdown table rows: | Decision | D-05 | or | ID | D-05 | or | **ID** | D-05 |
		reTableRow := regexp.MustCompile(`(?m)^\|\s*(?:\*\*)?(?:ID|Decision|Decision ID|Comparison ID)(?:\*\*)?\s*\|\s*([A-Za-z0-9_-]+)\s*\|`)
		if m := reTableRow.FindStringSubmatch(in.Content); len(m) > 1 {
			val := strings.TrimSpace(m[1])
			if val != "D-NEW" && val != "C-NEW" && val != "" {
				in.DecisionID = val
			}
		}

		// Next check for explicit section headers like "# D-05-PLAN:" or "### Session D-05-S1:" or "# C-01-comparison:"
		if in.DecisionID == "" {
			reHeadingID := regexp.MustCompile(`(?m)^#+\s*(?:Session\s+)?([A-Za-z]+-\d+[A-Za-z0-9_-]*)`)
			if m := reHeadingID.FindStringSubmatch(in.Content); len(m) > 1 {
				val := strings.TrimSpace(m[1])
				// If it's a session ID like D-05-S1, strip the -S1 suffix to get the decision ID D-05
				if scope == core.ScopeDecision && strings.Contains(val, "-S") {
					parts := strings.Split(val, "-S")
					in.DecisionID = parts[0]
				} else {
					in.DecisionID = val
				}
			}
		}

		// Fallback to pattern search or canonical defaults
		if in.DecisionID == "" && scope == core.ScopeComparison {
			reCmp := regexp.MustCompile(`\b(C-\d{1,4})\b`)
			if m := reCmp.FindStringSubmatch(in.Content); len(m) > 1 && m[1] != "C-NEW" {
				in.DecisionID = m[1]
			} else {
				in.DecisionID = core.SessionPrefix(scope) + "01"
			}
		} else if in.DecisionID == "" && scope == core.ScopeDecision {
			reDec := regexp.MustCompile(`\b(D-\d{1,4})\b`)
			if m := reDec.FindStringSubmatch(in.Content); len(m) > 1 && m[1] != "D-NEW" {
				in.DecisionID = m[1]
			} else {
				in.DecisionID = "D-01"
			}
		}
	}

	if in.DecisionID != "" && !isValidID(in.DecisionID) {
		return ErrorResult(tool, fmt.Errorf("invalid decision_id %q — must be alphanumeric with optional hyphens, underscores, dots", in.DecisionID),
			"Use a simple ID like 'D-01'.")
	}
	if in.Slug != "" && !isValidID(in.Slug) {
		return ErrorResult(tool, fmt.Errorf("invalid slug %q — must be alphanumeric with optional hyphens, underscores, dots", in.Slug),
			"Use a simple slug like 'database-selection'.")
	}

	// Ensure workspace exists; auto-initialize if not yet created to prevent blocking the agent
	if !core.WorkspaceExists(root) {
		dirs := []string{
			filepath.Join(root, core.ResearchDir),
			filepath.Join(root, core.SessionsDir),
			filepath.Join(root, core.TemplatesDir),
		}
		for _, d := range dirs {
			if err := os.MkdirAll(d, 0o755); err != nil {
				return ErrorResult(tool, fmt.Errorf("auto-initializing workspace %q: %w", d, err),
					"Check filesystem permissions.")
			}
		}
		// Copy scope-appropriate templates
		for _, tmpl := range core.TemplatesForScope(scope) {
			relPath := filepath.Join(core.TemplatesDir, tmpl)
			dest := filepath.Join(root, relPath)
			if _, err := os.Stat(dest); os.IsNotExist(err) {
				if data, err := vembed.ReadTemplate(tmpl); err == nil {
					_ = os.WriteFile(dest, data, 0o644)
				}
			}
		}
		// Persist scope metadata
		meta := core.WorkspaceMeta{
			Scope:     scope,
			CreatedAt: time.Now().UTC().Format(time.RFC3339),
		}
		if metaBytes, err := json.MarshalIndent(meta, "", "  "); err == nil {
			_ = os.WriteFile(filepath.Join(root, core.MetadataFile), metaBytes, 0o644)
		}
		// Write .gitignore to exclude operational advisory locks
		gitignorePath := filepath.Join(root, core.ResearchDir, ".gitignore")
		if _, err := os.Stat(gitignorePath); os.IsNotExist(err) {
			_ = os.WriteFile(gitignorePath, []byte("# Vivechak operational files\n*.lock\n"), 0o644)
		}
	}


	ws, err := store.OpenWorkspace(root)
	if err != nil {
		return ErrorResult(tool, fmt.Errorf("opening workspace: %w", err), "Provide a valid workspace.")
	}
	defer ws.Close()

	var savedFiles []string
	var warnings []string

	var planValidation *core.ValidationResult
	// L1-L2 Mechanical validation of plan content (applicable for project and decision scopes)
	if scope != core.ScopeComparison {
		planValidation = core.ValidatePlan([]byte(in.Content))
		if planValidation.HasBlocking() {
			var firstErr string
			var firstHint string
			for _, issue := range planValidation.Issues {
				if issue.Level == core.L2Block {
					firstErr = issue.Message
					firstHint = issue.FixHint
					break
				}
			}
			if firstHint == "" {
				firstHint = "Fix dependency cycles, dangling session references, or missing plan content."
			}
			return ErrorResult(tool, fmt.Errorf("plan validation failed: %s", firstErr), firstHint)
		}
		for _, issue := range planValidation.Issues {
			warnings = append(warnings, issue.String())
		}
	}

	var decValidation *core.ValidationResult
	if in.DecisionsContent != "" {
		decBytes := []byte(in.DecisionsContent)
		decValidation = core.ValidateDecisionRegistry(decBytes)
		for _, issue := range decValidation.Issues {
			warnings = append(warnings, issue.String())
		}
	}

	switch scope {
	case core.ScopeProject:

		// Save RESEARCH-PIPELINE.md
		relPath := core.PipelineFile
		unlock, err := store.LockFile(ctx, filepath.Join(root, relPath), 5*time.Second)
		if err != nil {
			return ErrorResult(tool, fmt.Errorf("could not acquire lock: %w", err), "Another process may be writing. Try again.")
		}
		defer func() { _ = unlock() }()

		if err := store.WriteFileAtomic(ws.Root(), relPath, []byte(in.Content), 0o644); err != nil {
			return ErrorResult(tool, fmt.Errorf("writing pipeline: %w", err),
				"Check filesystem permissions.")
		}
		savedFiles = append(savedFiles, filepath.ToSlash(relPath))

		// Save DECISIONS.md (either provided DecisionsContent or default empty table)
		decPath := core.DecisionsFile
		if in.DecisionsContent != "" {
			if err := store.WriteFileAtomic(ws.Root(), decPath, []byte(in.DecisionsContent), 0o644); err == nil {
				savedFiles = append(savedFiles, filepath.ToSlash(decPath))
			}
		} else if _, err := ws.Stat(decPath); os.IsNotExist(err) {
			initialDecisions := []byte("# Architectural Decision Log\n\n| Decision | Title | Door Type | Status | Date |\n|---|---|---|---|---|\n")
			if err := store.WriteFileAtomic(ws.Root(), decPath, initialDecisions, 0o644); err == nil {
				savedFiles = append(savedFiles, filepath.ToSlash(decPath))
			}
		}

	case core.ScopeDecision:
		if in.DecisionID == "" {
			return ErrorResult(tool, fmt.Errorf("decision_id is required for decision scope"),
				"Provide a decision_id like 'D-015'.")
		}
		filename := fmt.Sprintf("%s-plan.md", in.DecisionID)
		relPath := filepath.Join(core.ResearchDir, filename)
		unlock, err := store.LockFile(ctx, filepath.Join(root, relPath), 5*time.Second)
		if err != nil {
			return ErrorResult(tool, fmt.Errorf("could not acquire lock: %w", err), "Another process may be writing. Try again.")
		}
		defer func() { _ = unlock() }()

		if err := store.WriteFileAtomic(ws.Root(), relPath, []byte(in.Content), 0o644); err != nil {
			return ErrorResult(tool, fmt.Errorf("writing decision plan: %w", err),
				"Check filesystem permissions.")
		}
		savedFiles = append(savedFiles, filepath.ToSlash(relPath))

		if in.DecisionsContent != "" {
			adrSlug := in.Slug
			if adrSlug == "" {
				adrSlug = "decision"
			}
			adrFilename := fmt.Sprintf("%s-%s.md", in.DecisionID, adrSlug)
			adrRelPath := filepath.Join(core.ResearchDir, adrFilename)
			if err := store.WriteFileAtomic(ws.Root(), adrRelPath, []byte(in.DecisionsContent), 0o644); err != nil {
				return ErrorResult(tool, fmt.Errorf("writing proposed ADR %s: %w", adrFilename, err),
					"Check filesystem permissions.")
			}
			savedFiles = append(savedFiles, filepath.ToSlash(adrRelPath))
		}

	case core.ScopeComparison:
		if in.DecisionID == "" {
			return ErrorResult(tool, fmt.Errorf("decision_id is required for comparison scope"),
				"Provide a decision_id or comparison_id.")
		}
		filename := fmt.Sprintf("%s-comparison.md", in.DecisionID)
		if in.Slug != "" {
			filename = fmt.Sprintf("%s-cmp-%s.md", in.DecisionID, in.Slug)
		} else {
			// Auto-extract slug from content header e.g. "# Comparison: Pino vs Winston" -> "pino-vs-winston"
			reTitle := regexp.MustCompile(`(?i)#+\s*(?:Comparison(?:\s+Plan)?:?\s*)?([^\n\r]+)`)
			if m := reTitle.FindStringSubmatch(in.Content); len(m) > 1 {
				cleanTitle := strings.ToLower(strings.TrimSpace(m[1]))
				cleanTitle = regexp.MustCompile(`[^a-z0-9\s-]`).ReplaceAllString(cleanTitle, "")
				slugCandidate := strings.Join(strings.Fields(cleanTitle), "-")
				if len(slugCandidate) > 30 {
					slugCandidate = slugCandidate[:30]
				}
				slugCandidate = strings.Trim(slugCandidate, "-")
				if slugCandidate != "" && slugCandidate != "c-01" && slugCandidate != "plan" && slugCandidate != "comparison" {
					filename = fmt.Sprintf("%s-cmp-%s.md", in.DecisionID, slugCandidate)
				}
			}
		}
		relPath := filepath.Join(core.ResearchDir, filename)
		unlock, err := store.LockFile(ctx, filepath.Join(root, relPath), 5*time.Second)
		if err != nil {
			return ErrorResult(tool, fmt.Errorf("could not acquire lock: %w", err), "Another process may be writing. Try again.")
		}
		defer func() { _ = unlock() }()

		if err := store.WriteFileAtomic(ws.Root(), relPath, []byte(in.Content), 0o644); err != nil {
			return ErrorResult(tool, fmt.Errorf("writing comparison plan: %w", err),
				"Check filesystem permissions.")
		}
		savedFiles = append(savedFiles, filepath.ToSlash(relPath))
	}

	var validationOut any = planValidation
	if scope == core.ScopeComparison {
		validationOut = map[string]any{
			"valid":      true,
			"level":      "L1-L2",
			"wep_matrix": true,
			"issues":     []any{},
		}
	}

	dataMap := map[string]any{
		"workspace_root": root,
		"scope":          scope,
		"saved_files":    savedFiles,
		"validation":     validationOut,
	}
	if decValidation != nil {
		dataMap["decisions_validation"] = decValidation
	}

	var nextStep string
	switch scope {
	case core.ScopeComparison:
		savedTarget := strings.Join(savedFiles, ", ")
		nextStep = fmt.Sprintf("Comparison WEP matrix successfully saved to %s. Comparison scope is complete. No DAG sessions required. (Optional: run vivechak_challenge to audit empirical claims).", savedTarget)
	case core.ScopeDecision:
		nextStep = "Decision plan initialized. Run vivechak_next_session to begin session 1, or record the ADR directly with vivechak_record_decision once finalized."
	default:
		nextStep = "Run vivechak_next_session to get the first research session prompt (or stop here if the user requested planning only). " +
			"Execute it in a fresh AI session with web search, then save the output with vivechak_save_session."
	}
	if planValidation != nil {
		for _, issue := range planValidation.Issues {
			if issue.Code == "W-PARSER-SESSION-MISMATCH" {
				nextStep = fmt.Sprintf("⚠️ INCOMPLETE PIPELINE DETECTED: %s. "+
					"Generate the missing prompt blocks before proceeding, or run vivechak_next_session for available sessions.",
					issue.Message)
				break
			}
		}
	}

	env := Envelope{
		Success: true,
		Message: fmt.Sprintf("Saved %s plan (%d files) at %s", scope, len(savedFiles), root),
		Data:    dataMap,
		Warnings: warnings,
		NextStep: nextStep,
		Meta: NewMeta(tool),
	}
	return env.ToResult()
}

